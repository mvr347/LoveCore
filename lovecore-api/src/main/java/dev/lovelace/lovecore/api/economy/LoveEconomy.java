package dev.lovelace.lovecore.api.economy;

import org.bukkit.entity.Player;

import java.util.List;

/**
 * Единая валюта экосистемы — физические предметы ItemsAdder в инвентаре игрока, а не запись
 * в базе. У игрока нет виртуального баланса: сколько у него денег — это сколько монет у него
 * физически лежит в инвентаре.
 *
 * <p>Из этого следует главное отличие от обычного «кошелька»: операции возможны только для
 * онлайн-игрока (нужен доступ к живому инвентарю), офлайн-баланса не существует. Клановая
 * казна — не часть этого интерфейса: она остаётся отдельным хранимым числом на стороне
 * LoveClans, пополняемым и расходуемым через {@link #charge}/{@link #give} у живого игрока.</p>
 *
 * <p>{@link #charge} умеет разменивать: если у игрока есть только более крупный номинал, чем
 * нужно списать, монета разбивается и остаток выдаётся обратно мелкими номиналами — так же,
 * как оплата бумажной купюрой со сдачей.</p>
 */
public interface LoveEconomy {

    /** Название валюты для показа игроку. */
    String currencyName();

    /** Номиналы монет от старшего к младшему — то, чем считает и {@link #charge}, и {@link #give}. */
    List<Denomination> denominations();

    /** Сколько единиц валюты у игрока физически в инвентаре прямо сейчас. */
    long balance(Player player);

    /** Хватит ли у игрока монет на сумму, без списания. */
    boolean has(Player player, long amount);

    /**
     * Списывает сумму монетами из инвентаря, разменивая при необходимости.
     *
     * @return {@code false}, если монет не хватило — в этом случае инвентарь не тронут
     */
    boolean charge(Player player, long amount);

    /**
     * Выдаёт сумму монетами в инвентарь, минимальным числом предметов (сначала старшие
     * номиналы). Если место в инвентаре кончилось на середине выдачи, уже выданное остаётся
     * у игрока, а оставшиеся монеты падают под ноги — начатая выдача не откатывается, это уже
     * реальные предметы в чужом инвентаре.
     */
    void give(Player player, long amount);

    /** Поместится ли сумма монетами в инвентарь без учёта выпадения на землю. */
    boolean canFit(Player player, long amount);
}
